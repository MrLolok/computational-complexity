"""Controlli delle interazioni con Playwright Python già installato. Server su :3000."""
from pathlib import Path
from playwright.sync_api import sync_playwright, expect

with sync_playwright() as p:
    executable = next((Path.home() / '.cache/ms-playwright').glob('chromium-1223/chrome-linux64/chrome'), None)
    browser = p.chromium.launch(headless=True, **({'executable_path': str(executable)} if executable else {}))
    context = browser.new_context(viewport={'width':1440, 'height':1000})
    page = context.new_page()
    errors = []
    page.on('pageerror', lambda e: errors.append(str(e)))
    def visit(path):
        response = page.goto('http://localhost:3000' + path, wait_until='networkidle')
        assert response is None or response.status == 200, (path, response.status if response else None)
        expect(page.locator('main h1')).to_have_count(1)
        expect(page.locator('.katex-error')).to_have_count(0)
        assert page.locator('main .font-mono, main code, main pre').evaluate_all('(els) => els.every(e => getComputedStyle(e).fontFamily === getComputedStyle(document.body).fontFamily)'), 'monospaced font remains'
        expect(page.get_by_role('navigation', name='Sezioni').locator('[aria-current=page]')).to_have_count(1) if path != '/fonti' else None
    def no_overflow():
        assert page.evaluate('document.documentElement.scrollWidth <= innerWidth'), 'page overflow'

    visit('/')
    page.get_by_role('tab',name='Probabilistiche',exact=True).click()
    expect(page.locator('#BPP')).to_be_visible()
    page.get_by_role('tab', name='Quantistiche', exact=True).click()
    expect(page.locator('#BQP')).to_be_visible()
    page.get_by_role('tab', name='Le basi').click()
    page.screenshot(path='/tmp/cc-home-desktop.png',full_page=True)
    visit('/confronta')
    page.locator('#cmpA').select_option('P')
    page.locator('#cmpB').select_option('NP')
    assert page.url.endswith('/confronta')
    page.get_by_role('button',name='Confronta →',exact=True).click()
    page.wait_for_url('**/confronta/P/NP')
    expect(page.get_by_text('P è contenuta in NP. Non sappiamo se le due classi siano uguali.',exact=True)).to_be_visible()
    visit('/teoremi')
    count = page.locator('details[id^="teorema-"]').count()
    page.get_by_label('Solo dimostrati nel corso').check()
    filtered = page.locator('details[id^="teorema-"]').count()
    assert 0 < filtered < count
    assert page.locator('details[id^="teorema-"]').get_by_text('dimostrato nel corso',exact=True).count() == filtered
    visit('/piani')
    page.get_by_role('button',name='Piano 2').click()
    expect(page.get_by_role('heading',name='Esiste una scelta x che funziona per ogni scelta y?')).to_be_visible()
    assert not page.locator('#towercard').is_visible()
    visit('/piani#S2')
    expect(page.locator('#towercard')).to_be_visible()
    visit('/quantistico')
    page.get_by_label('Raddoppia la chiave contro Grover (256 bit)').check()
    assert page.locator('#grover sup').all_text_contents() == ['128','128']
    visit('/tracce/F03')
    page.get_by_role('button',name='Correggi subito').click()
    page.locator('#d6').get_by_role('button',name='SÌ',exact=True).click()
    expect(page.locator('#d6').get_by_text('Risposta:',exact=True)).to_be_visible()
    assert '🔁' not in page.locator('main').inner_text()
    assert 'Provenienza della traccia' not in page.locator('main').inner_text()
    badge = page.locator('#d6').get_by_text('Risposta:',exact=True).locator('..')
    assert badge.evaluate('(e) => Math.abs(e.children[0].getBoundingClientRect().y - e.children[1].getBoundingClientRect().y) < 8'), 'answer label wraps'
    term = page.locator('#d6 [data-term="symmetric"]').first
    term.focus()
    expect(page.get_by_role('dialog')).to_be_visible()
    page.get_by_role('dialog').locator('p').hover()
    page.wait_for_timeout(300)
    expect(page.get_by_role('dialog')).to_be_visible()
    page.keyboard.press('Escape')
    expect(page.get_by_role('dialog')).to_have_count(0)
    visit('/tracce/F04')
    page.get_by_role('button',name='Correggi subito').click()
    page.locator('#d2').get_by_role('button',name='SÌ',exact=True).click()
    expect(page.locator('#d2').get_by_text('Vedi anche:',exact=False)).to_be_visible()
    assert 'stessa domanda' not in page.locator('#d2').inner_text().lower()
    visit('/problemi/REACH')
    expect(page.get_by_text('Problema 1 di 36',exact=True)).to_be_visible()
    carousel = page.locator('[aria-roledescription="carosello"]')
    expect(carousel.get_by_role('button',name='Immagine precedente')).to_be_disabled()
    carousel.get_by_role('button',name='Immagine successiva').click()
    expect(carousel.get_by_role('button',name='Passo 2: Esplora i successori')).to_have_attribute('aria-pressed','true')
    carousel.get_by_role('button',name='Immagine successiva').click()
    expect(carousel.get_by_text('Sì: D è raggiungibile da A.',exact=True)).to_be_visible()
    expect(carousel.get_by_role('button',name='Immagine successiva')).to_be_disabled()
    page.get_by_role('button',name='Prossimo →',exact=True).click()
    page.wait_for_url('**/problemi/SAT2')
    expect(page.get_by_text('Problema 2 di 36',exact=True)).to_be_visible()
    expect(page.locator('[aria-roledescription="carosello"]').get_by_role('button',name='Immagine precedente')).to_be_disabled()
    page.screenshot(path='/tmp/cc-problems-desktop.png',full_page=True)
    catalog = page.locator('#problem-list')
    assert catalog.evaluate('(e)=>e.scrollHeight > e.clientHeight && getComputedStyle(e).position === "sticky"'), 'catalog should scroll and remain sticky'
    expect(catalog.locator('[data-term]')).to_have_count(0)
    row = catalog.get_by_role('button').first
    row.hover()
    page.wait_for_timeout(250)
    expect(page.get_by_role('dialog')).to_have_count(0)
    before = page.evaluate('scrollY')
    catalog.hover()
    page.mouse.wheel(0, 600)
    page.wait_for_timeout(250)
    assert catalog.evaluate('(e)=>e.scrollTop > 0'), 'catalog wheel does not scroll'
    assert abs(page.evaluate('scrollY') - before) < 2, 'catalog wheel moves detail panel'
    assert page.locator('#problem-detail').evaluate('(e)=>e.scrollHeight <= e.clientHeight'), 'problem box scrolls internally'
    page.get_by_label('Solo nelle tracce').check()
    rows = page.locator('[aria-controls=problem-detail]')
    assert all('Nelle tracce' in row.inner_text() for row in rows.all())
    page.get_by_label('Solo nelle tracce').uncheck()
    page.get_by_label('Cerca un problema').fill('SAT')
    assert page.locator('[aria-controls="problem-detail"]').first.inner_text().startswith('02'), 'numbering changes with filter'
    page.get_by_label('Cerca un problema').fill('QSAT')
    expected = page.locator('#problem-list button').first
    expected.click()
    next_name = page.locator('#problem-list button').nth(1).inner_text()
    page.get_by_role('button', name='Prossimo →', exact=True).click()
    expect(page.locator('#problem-list button').nth(1)).to_have_attribute('aria-pressed', 'true')
    expect(page.get_by_label('Cerca un problema')).to_have_value('QSAT')
    visit('/problemi/IS')
    expect(page.locator('#problem-detail').get_by_text('Indipendente non significa isolato:', exact=True)).to_be_visible()
    expect(page.locator('#problem-detail')).to_contain_text('{A, B} non va bene')
    visit('/tracce/L18')
    page.get_by_role('button',name='Correggi subito').click()
    page.locator('#d6').get_by_role('button',name='SÌ',exact=True).click()
    expect(page.locator('#d6')).to_contain_text('n è la lunghezza dell’intero input in bit')
    expect(page.locator('#d6')).to_contain_text('Quanto è grande l’input?')
    expect(page.locator('#d6 .katex-error')).to_have_count(0)
    visit('/fonti')
    visit('/esercizi')

    page.set_viewport_size({'width':390,'height':844})
    for path in ['/', '/classi', '/confronta/P/NP', '/problemi/REACH', '/teoremi', '/piani', '/quantistico', '/tracce/F03', '/fonti', '/esercizi']:
        visit(path)
        no_overflow()
        page.screenshot(path='/tmp/cc-mobile-'+path.strip('/').replace('/','-')+'.png',full_page=True)
    visit('/problemi/REACH')
    expect(page.locator('#problem-list')).to_be_hidden()
    page.get_by_role('button', name='Mostra elenco dei problemi').click()
    expect(page.locator('#problem-list')).to_be_visible()
    page.locator('#problem-list button').nth(1).click()
    page.wait_for_url('**/problemi/SAT2')
    expect(page.locator('#problem-list')).to_be_hidden()
    expect(page.locator('#problem-detail')).to_be_focused()
    assert not errors, errors
    print('OK: home tabs, comparison, theorem filter, PH, Grover, clean answers, popups, slideshow, next problem, stable numbers, mobile overflow.')
    context.close()
    browser.close()
